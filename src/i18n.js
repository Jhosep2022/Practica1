function fallbackCategoryName(slug) {
  return slug.charAt(0).toUpperCase() + slug.slice(1).replace(/-/g, ' ')
}

export function getMessages(language) {
  const dictionary = messages[language] || messages.es

  const locale = language === 'en' ? 'en-US' : 'es-BO'

  return {
    ...dictionary,
    locale,
    productTitle: (product) =>
      (language === 'es' && productNamesEs[product.id]) || product.title,
    category: (slug) => categoryNames[language]?.[slug] || fallbackCategoryName(slug),
    money: (value) =>
      new Intl.NumberFormat(locale, {
        style: 'currency',
        currency: 'USD',
        currencyDisplay: 'narrowSymbol',
      }).format(value),
  }
}
